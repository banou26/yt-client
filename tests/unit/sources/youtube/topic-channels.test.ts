import { describe, expect, it } from 'vite-plus/test'

// via the package surface: `exports` does not publish dist/, so a deep import does not resolve
import { Parser, YT } from 'youtubei.js'

import { createYoutubeSource } from '../../../../src/sources/youtube'
import fixture from '../../fixtures/topic-channels.json'

/* topic-channels.json holds the signed-out browses of youtube.com's topic channels captured on 2026-11-10 (English,
   United States; News also as Hong Kong and Czechia answer it) and of the first game Gaming lists, cut to one item per
   row and stripped of tracking fields. They run through the real upstream parser as this repo patches it. The Channel
   has no actions, so a tab looked up rather than read as it landed throws. */

const sourceFor = (answer: unknown) => createYoutubeSource({
  fetch: globalThis.fetch,
  createClient: async () => ({
    getChannel: async () => new YT.Channel(undefined as never, Parser.parseResponse(answer as never), true),
  }) as never,
})

describe('topic channels', () => {
  it('opens Live on the Home it landed on, whose tab has no URL to look it up by', async () => {
    const page = await sourceFor(fixture.live).channel('UC4R8DWoMoI7CAwX8_LjQHig')
    expect(page.tab).toBe('HOME')
    expect(page.availableTabs).toEqual([])
    expect(page.channel).toMatchObject({ id: 'UC4R8DWoMoI7CAwX8_LjQHig', name: 'Live', avatar: expect.stringContaining('=s208') })
    expect(page.home?.shelves.map((shelf) => shelf.title)).toEqual(['Live Now', 'Recent Live Streams'])
    const [now] = page.home?.shelves ?? []
    expect(now).toMatchObject({
      expandable: true,
      videos: [{ id: 'DxgDeW-gIcU', isLive: true, viewCount: '342K watching', channel: { name: 'HotSpanish Vlogs' } }],
    })
    // youtube.com's own livetab browse, which no route here opens
    expect(now?.url).toBeUndefined()
  })

  it('reads Music\'s rich grid, which the answer sends after an empty section list', async () => {
    const page = await sourceFor(fixture.music).channel('UC-9-kyTW8ZkZNDHQJ6FgpwQ')
    expect(page.tab).toBe('HOME')
    expect(page.availableTabs).toEqual(['HOME', 'COMMUNITY'])
    // the header's name, over the microformat's "The Music Channel"
    expect(page.channel).toMatchObject({ name: 'Music', subscriberCountText: '128M subscribers' })
    const [songs, rising] = page.home?.shelves ?? []
    expect(songs).toMatchObject({
      title: 'New & Trending Songs',
      expandable: true,
      videos: [],
      playlists: [{ id: 'RDCLAK5uy_k5n4srrEB1wgvIjPNTXS9G1ufE9WQxhnA', title: 'RELEASED', videoCountText: '79 songs' }],
    })
    expect(rising).toMatchObject({
      title: 'Artist On The Rise Trending',
      url: '/playlist?list=OLJBWz2Zk1hmY6R12VywQTbNCe_pNW_E69Q',
      videos: [{ id: 'gpverHkcoOY', viewCount: '535K', publishedText: '2w ago', channel: { name: 'thekidszn' } }],
    })
  })

  it('reads Gaming\'s rows: a shelf, then card lists of games by their box art and of videos', async () => {
    const page = await sourceFor(fixture.gaming).channel('UCOpNcN46UbXVtpKMrmU4Abg')
    expect(page.tab).toBe('HOME')
    expect(page.channel.name).toBe('Gaming')
    const [featured, games, trending] = page.home?.shelves ?? []
    expect(featured).toMatchObject({ title: 'Featured', videos: [{ id: 'mtjtRsb6_is', channel: { name: 'Chuy Mine' } }] })
    expect(games).toMatchObject({
      title: 'Top live games',
      subtitle: 'Auto-generated by YouTube',
      games: [{ id: 'UCOquqcRMJmURiGfEnaitptg', title: 'Grand Theft Auto V', boxArt: expect.stringContaining('yt3.googleusercontent.com') }],
    })
    expect(games?.expandable).toBeUndefined()
    expect(trending).toMatchObject({
      title: 'Trending videos',
      subtitle: 'Hot and fresh',
      videos: [{ id: 'gf50dvLAORc', viewCount: '3.5M views', publishedText: 'Streamed 13h ago', channel: { name: 'LoL Esports' } }],
    })
  })

  // a game's Home is /channel/UC.../home, a word youtubei.js has no tab for, beside an About it does have
  it('opens a game, as Gaming\'s tiles link it, on the Home it landed on rather than its About', async () => {
    const page = await sourceFor(fixture.game).channel('UCOquqcRMJmURiGfEnaitptg')
    expect(page.availableTabs).toEqual(['ABOUT'])
    expect(page.tab).toBe('HOME')
    // the header's name, over the microformat's "Grand Theft Auto V - Topic"
    expect(page.channel).toMatchObject({ name: 'Grand Theft Auto V', avatar: expect.stringContaining('yt3.googleusercontent.com') })
    expect(page.home?.shelves).toMatchObject([
      { title: 'Live', videos: [{ id: 'SpssutPTWqE', viewCount: '703 watching' }] },
      { title: 'Recommended' },
    ])
    // a live card's one line has no date
    expect(page.home?.shelves[0]?.videos[0]?.publishedText).toBeUndefined()
  })

  it('names Sports off its carousel header, the answer carrying no metadata', async () => {
    const page = await sourceFor(fixture.sports).channel('UCEgdi0XIXXZ-qJOFPf4JSKw')
    expect(page.channel).toMatchObject({ name: 'Sports', subscriberCountText: '74.2M subscribers', avatar: expect.stringContaining('yt3.googleusercontent.com') })
    expect(page.home?.shelves).toMatchObject([{ title: 'Trending', expandable: true, videos: [{ id: 'R-0lV62Xs40' }] }])
  })

  it('reads News as each region answers it: posts in Hong Kong, upstream\'s own line in Czechia', async () => {
    const hongKong = await sourceFor(fixture.newsHongKong).channel('UCYfdidRxbB8Qhf0Nx7ioOYw')
    expect(hongKong.channel.name).toBe('News')
    expect(hongKong.home?.shelves).toMatchObject([{
      title: 'Latest news posts',
      posts: [{ id: 'UgkxVbNyGruvVOBe9ImiED0LNY0l3xRyYgNN', author: { id: 'UCqUhYNPzxfRwD73W84xMUSQ' }, text: expect.stringContaining('Nvidia') }],
    }])
    const czechia = await sourceFor(fixture.newsCzechia).channel('UCYfdidRxbB8Qhf0Nx7ioOYw')
    expect(czechia.home).toEqual({ shelves: [], message: 'This page is not available.' })
  })
})
